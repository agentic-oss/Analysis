import os
import json
import logging
from typing import Dict, Any, List
import pandas as pd

logger = logging.getLogger(__name__)

class ReportGenerator:
    """
    Generates structured daily Markdown report (reports/daily/YYYY-MM-DD.md)
    and daily machine-readable JSON report (data/analysis/daily/YYYY-MM-DD.json).
    """

    @staticmethod
    def generate_json_report(date_str: str, gold_data: Dict[str, Any], silver_data: Dict[str, Any], ratio_data: Dict[str, Any], macro_data: Dict[str, Any], quality_data: Dict[str, Any], alerts: List[Dict[str, Any]]) -> Dict[str, Any]:
        return {
            "date": date_str,
            "gold": gold_data,
            "silver": silver_data,
            "gold_silver_ratio": {
                "current": ratio_data.get("current_gold_silver_ratio"),
                "z_score": ratio_data.get("z_score"),
                "percentile": ratio_data.get("percentile"),
                "signal": ratio_data.get("mean_reversion_signal")
            },
            "macro": macro_data,
            "data_quality": quality_data,
            "alerts": alerts
        }

    @staticmethod
    def generate_markdown_report(date_str: str, gold_data: Dict[str, Any], silver_data: Dict[str, Any], ratio_data: Dict[str, Any], macro_data: Dict[str, Any], quality_data: Dict[str, Any], alerts: List[Dict[str, Any]]) -> str:

        md = f"""# Precious Metals Daily Research Report — {date_str}

## Executive Summary

**Gold:**
- Price: ${gold_data.get('price', 0):,.2f} USD/oz | ₹{gold_data.get('inr_price', 0):,.2f} INR/10g
- Daily Move: {gold_data.get('return_1d_pct', 0):+.2f}%
- 20D Trend: {gold_data.get('regime', {}).get('trend', 'N/A')}
- Volatility: {gold_data.get('regime', {}).get('volatility', 'N/A')}
- Research Bias: {gold_data.get('research_bias', 'Neutral')} (Composite Score: {gold_data.get('composite_score', 50):.1f}/100)

**Silver:**
- Price: ${silver_data.get('price', 0):,.2f} USD/oz | ₹{silver_data.get('inr_price', 0):,.2f} INR/kg
- Daily Move: {silver_data.get('return_1d_pct', 0):+.2f}%
- 20D Trend: {silver_data.get('regime', {}).get('trend', 'N/A')}
- Research Bias: {silver_data.get('research_bias', 'Neutral')} (Composite Score: {silver_data.get('composite_score', 50):.1f}/100)

---

## Gold Analysis

### Technical & Macro Structure
- Composite Score: {gold_data.get('composite_score', 50)}
- Technical Score: {gold_data.get('scores', {}).get('technical_score', 50)}
- Macro Score: {gold_data.get('scores', {}).get('macro_score', 50)}
- Regime: {gold_data.get('regime', {}).get('composite_regime', 'N/A')}

### Forward Probabilities & Statistics
"""
        fwd = gold_data.get("signals", {})
        for h, sig in fwd.items():
            if isinstance(sig, dict):
                md += f"- **{h}**: Prob Positive: {sig.get('prob_positive_return')}%, Exp Return: {sig.get('expected_return_pct'):+.2f}%, Confidence: {sig.get('confidence_score')}/100\n"

        md += f"""
---

## Silver Analysis & Relative Value

- **Gold/Silver Ratio:** {ratio_data.get('current_gold_silver_ratio', 0):.2f} (Z-Score: {ratio_data.get('z_score', 0):+.2f}, Historical Percentile: {ratio_data.get('percentile', 0):.1f}%)
- **Relative Value Signal:** {ratio_data.get('mean_reversion_signal', 'Neutral')}

---

## Macro Environment

- Primary Macro Regime: {macro_data.get('macro_regime', {}).get('primary_macro_regime', 'N/A')}
- Risk Regime: {macro_data.get('macro_regime', {}).get('risk_regime', 'N/A')}
- Monetary Stance: {macro_data.get('macro_regime', {}).get('monetary_regime', 'N/A')}
- DXY Trend: {macro_data.get('macro_regime', {}).get('dxy_trend_20d', 'N/A')}

---

## Alerts Triggered

"""
        if alerts:
            for a in alerts:
                md += f"- **[{a.get('severity')}] {a.get('type')}**: {a.get('message')}\n"
        else:
            md += "- No threshold alerts triggered for today.\n"

        md += f"""
---

## Data Quality Summary

- Total records checked: {quality_data.get('total_records_checked', 0)}
- Overall Data Quality Status: **{quality_data.get('overall_status', 'PASSED')}**

*Disclaimer: All output generated by this system consists strictly of probabilistic research signals based on historical conditional statistics and quantitative models. No guaranteed future prices are implied or provided.*
"""
        return md
